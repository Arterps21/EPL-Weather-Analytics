CREATE TABLE IF NOT EXISTS teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS matches (
    match_id TEXT PRIMARY KEY,

    season VARCHAR(20) NOT NULL,
    match_date DATE NOT NULL,
    kickoff_utc TIMESTAMPTZ,

    home_team_id INTEGER NOT NULL REFERENCES teams(id),
    away_team_id INTEGER NOT NULL REFERENCES teams(id),

    stadium_name VARCHAR(200),

    home_goals SMALLINT NOT NULL,
    away_goals SMALLINT NOT NULL,

    home_xg DOUBLE PRECISION,
    away_xg DOUBLE PRECISION,

    home_shots SMALLINT,
    away_shots SMALLINT,

    home_shots_on_target SMALLINT,
    away_shots_on_target SMALLINT,

    CONSTRAINT different_teams
        CHECK (home_team_id <> away_team_id),

    CONSTRAINT non_negative_goals
        CHECK (home_goals >= 0 AND away_goals >= 0),

    CONSTRAINT non_negative_stats
        CHECK (
            (home_xg IS NULL OR home_xg >= 0)
            AND (away_xg IS NULL OR away_xg >= 0)
            AND (home_shots IS NULL OR home_shots >= 0)
            AND (away_shots IS NULL OR away_shots >= 0)
            AND (home_shots_on_target IS NULL OR home_shots_on_target >= 0)
            AND (away_shots_on_target IS NULL OR away_shots_on_target >= 0)
        ),

    CONSTRAINT unique_season_fixture
        UNIQUE (season, home_team_id, away_team_id)
);


CREATE INDEX IF NOT EXISTS idx_matches_season
    ON matches(season);

CREATE INDEX IF NOT EXISTS idx_matches_home_team
    ON matches(home_team_id);

CREATE INDEX IF NOT EXISTS idx_matches_away_team
    ON matches(away_team_id);